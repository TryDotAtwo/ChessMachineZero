namespace {

constexpr std::array<std::uint8_t, 107> kArtifact = {
    0x43, 0x4d, 0x5a, 0x56, 0x4d, 0x30, 0x30, 0x31, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x33, 0x00, 0x00, 0x00,
    0xfd, 0xef, 0xe2, 0x8f, 0xb5, 0x9a, 0xd8, 0xe3, 0x87, 0x0b, 0x8b, 0x22,
    0x23, 0xbf, 0x14, 0xce, 0x95, 0x42, 0x16, 0x3c, 0x5e, 0x66, 0x66, 0xe6,
    0xf8, 0xc7, 0x99, 0xce, 0x63, 0x09, 0xa6, 0x79, 0x01, 0x00, 0x02, 0x00,
    0x04, 0x00, 0x01, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x00, 0x00, 0x77, 0x00, 0x00, 0x80, 0x3f, 0x10, 0x32, 0x07,
    0x00, 0x01, 0x01, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
    0x00, 0x00, 0x00, 0xfd, 0x07, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00,
};

}  // namespace

int main() {
    const auto artifact = cmz::Artifact::from_bytes(kArtifact);
    if (artifact.tensors().size() != 1 || artifact.operations().size() != 1) {
        return 1;
    }
    const auto& tensor = artifact.tensors().front();
    if (tensor.name != "w" || tensor.shape != std::vector<std::uint32_t>({2, 2}) ||
        tensor.packed != std::vector<std::uint8_t>({0x10, 0x32}) ||
        tensor.scales != std::vector<float>({1.0F}) || tensor.block_size != 4) {
        return 2;
    }
    const auto& operation = artifact.operations().front();
    if (operation.opcode != cmz::OpCode::RowRoute || operation.inputs != std::vector<std::uint32_t>({0}) ||
        operation.outputs != std::vector<std::uint32_t>({1}) ||
        operation.attributes != std::vector<std::uint32_t>({2045, 2048})) {
        return 3;
    }
    return 0;
}
